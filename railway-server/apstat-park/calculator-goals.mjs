export const GOALS = Object.fromEntries(Object.entries(SPANS)
  .map(([problemId, spans]) => [problemId, spans.flatMap(([goal, count]) => Array(count).fill(goal))]));

export function goalFor(problemId, step) {
  return GOALS[problemId]?.[step] ?? null;
}

// Runs of steps that share a goal: [{ from, to, goal }], from and to inclusive.
export function goalSpans(problemId) {
  const goals = GOALS[problemId];
  if (!goals) return [];
  const spans = [];
  goals.forEach((goal, step) => {
    const last = spans.at(-1);
    if (last && last.goal === goal) last.to = step;
    else spans.push({ from: step, to: step, goal });
  });
  return spans;
}
